import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { copyFile, mkdir } from "node:fs/promises";
import path from "node:path";

const mode = process.argv[2];
const prod = mode === "production" || mode === "demo";

const context = await esbuild.context({
  banner: {
    js: "/* Generated by esbuild. Source: https://github.com/caijyii/obsidian-tab-cleaner */",
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  await context.dispose();
}

if (mode === "demo") {
  const demoPluginDir = path.join("demo-vault", ".obsidian", "plugins", "tab-cleaner");
  await mkdir(demoPluginDir, { recursive: true });
  await Promise.all(
    ["main.js", "manifest.json", "styles.css"].map((file) =>
      copyFile(file, path.join(demoPluginDir, file)),
    ),
  );
}

if (!prod) {
  await context.watch();
}
